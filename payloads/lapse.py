def pin_to_core(core):
    level = 3
    which = 1
    id = 0xFFFFFFFFFFFFFFFF  # -1
    setsize = 0x10
    mask = alloc(0x10)
    mask[0:2] = struct.pack("<H", 1 << core)
    return sc.syscalls.cpuset_setaffinity(level, which, id, setsize, mask)


def get_core_index(mask_addr):
    num = readuint(mask_addr, 4)
    pos = 0
    while num > 0:
        num >>= 1
        pos += 1

    return pos - 1


