def rtprio(type_, prio=0):
    PRI_REALTIME = 2
    rtprio_buf = alloc(4)
    rtprio_buf[0:2] = struct.pack("<H", PRI_REALTIME)
    rtprio_buf[2:4] = struct.pack("<H", prio)
    sc.syscalls.rtprio_thread(type_, 0, rtprio_buf)
    if type_ == RTP_LOOKUP:
        return struct.unpack("<H", rtprio_buf[2:4])[0]


